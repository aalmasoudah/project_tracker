def replace_text_node(node: object, value: str) -> None:
    parent = node.getparent()
    original = str(node)
    prefix = original[: len(original) - len(original.lstrip())]
    suffix = original[len(original.rstrip()) :]
    replacement = f"{prefix}{value}{suffix}"
    if node.is_text:
        parent.text = replacement
    else:
        parent.tail = replacement


def build() -> None:
    document = html.fromstring(SOURCE.read_text(encoding="utf-8"))
    document.set("lang", "ar")
    document.set("dir", "rtl")
    style = document.xpath("//style")[0]
    style.text += "\nbody{direction:rtl;text-align:right} .notes{text-align:right;left:4vw;right:4vw} .brand-mini{direction:rtl} .controls{direction:ltr} .screen figcaption{text-align:right}\n"
    slides = document.xpath(
        '//section[contains(concat(" ", normalize-space(@class), " "), " slide ")]'
    )
    if len(slides) != len(SLIDE_TEXTS):
        raise ValueError(f"Expected {len(SLIDE_TEXTS)} slides, found {len(slides)}")
    for index, (slide, translations) in enumerate(
        zip(slides, SLIDE_TEXTS, strict=True), 1
    ):
        nodes = slide.xpath(".//text()[normalize-space()]")
        if len(nodes) != len(translations):
            raise ValueError(
                f"Slide {index}: expected {len(translations)} text nodes, found {len(nodes)}"
            )
        for node, translation in zip(nodes, translations, strict=True):
            replace_text_node(node, translation)
        slide.set("data-title", translations[1])
        for image in slide.xpath(".//img"):
            image.set("alt", "صورة توضيحية من نظام إنسايت تراكر")
        footer_spans = slide.xpath(
            './/div[contains(concat(" ", normalize-space(@class), " "), " footer ")]/span'
        )
        if footer_spans:
            footer_spans[-1].set("dir", "ltr")

    controls = document.xpath(
        '//div[contains(concat(" ", normalize-space(@class), " "), " controls ")]'
    )[0]
    controls.set("aria-label", "أدوات التحكم في العرض")
    buttons = controls.xpath(".//button")
    labels = ["الشريحة السابقة", "إظهار أو إخفاء ملاحظات المتحدث", "الشريحة التالية"]
    for button, label in zip(buttons, labels, strict=True):
        button.set("aria-label", label)
    buttons[1].set("title", "ملاحظات المتحدث (N)")
    title = document.xpath("//title")[0]
    title.text = "إنسايت تراكر - عرض مدير التقنية لمدة 15 دقيقة"

    rendered = "<!doctype html>\n" + html.tostring(
        document, encoding="unicode", method="html"
    )
    rendered = re.sub(
        r"<html([^>]*)>", lambda m: '<html lang="ar" dir="rtl">', rendered, count=1
    )
    OUTPUT.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    build()
